def main():
    # Fixed order, not alphabetical - draw_char in src/menu.s computes this
    # index with arithmetic (space=0, '0'-'9'=1..10, 'A'-'Z'=11..36, cursor=37)
    # instead of a second lookup table, so the order here has to match that
    # arithmetic exactly.
    order = [' '] + list("0123456789") + list("ABCDEFGHIJKLMNOPQRSTUVWXYZ") + ['\x01']
    assert len(order) == 38

    for ch in order:
        rows = GLYPHS[ch]
        assert len(rows) == 7, ch
        assert all(len(r) == 5 for r in rows), ch

    label = {' ': 'space', '\x01': 'cursor'}

    print("menu_chars")
    for ch in order:
        name = label.get(ch, ch)
        print(f"\tdc.l\tmchar_{name}")
    print()

    for i, ch in enumerate(order):
        name = label.get(ch, ch)
        print(f"mchar_{name}\t\t\t; index {i}")
        for row in GLYPHS[ch]:
            words = ", ".join("-1" if c == "#" else "0" for c in row)
            print(f"\tdc.w\t{words}")


if __name__ == "__main__":
    main()
